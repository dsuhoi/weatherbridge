#!/usr/bin/env python3
"""Build the LaTeX table for the S-DYff ensemble HF-blur experiment.

Reads ``metrics/sh_spectra_ens/<prefix>_summary.json`` (produced by
``sh_spectra_ens_sdyff.py``) and writes ``paper/tab_sh_ens_blur.tex``.

The table shows per-channel R_HF for {GT, single MC sample, ens-mean (N=16)}
plus a "blur" column = (R_HF_single - R_HF_ens) / R_HF_single * 100%.
"""
from __future__ import annotations

import argparse
import json
from pathlib import Path


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--summary",
                    default="metrics/sh_spectra_ens/sdyff_24ch_6yr_ens16_tau3_summary.json")
    ap.add_argument("--out", default="paper/tab_sh_ens_blur.tex")
    args = ap.parse_args()

    summary = json.loads(Path(args.summary).read_text())
    rows = summary["per_channel"]
    agg = summary.get("aggregate", {})
    tau = summary.get("tau_hours", "?")
    n_ens = summary.get("n_ensemble", "?")
    n_samp = summary.get("n_samples_accumulated", "?")

    lines = []
    lines.append("% Auto-generated by tools/eval/build_sh_ens_blur_table.py")
    lines.append(f"% Source: {args.summary}")
    lines.append(r"\begin{table}[t]")
    lines.append(r"\centering")
    lines.append(
        r"\caption{High-frequency energy ratio $R_{\mathrm{HF}} = "
        r"\sum_{\ell\geq 90} E(\ell) / \sum_\ell E(\ell)$ at $\tau=" + str(tau) + r"$\,h "
        r"for ground truth, a single MC-dropout sample, and the S-DYff "
        r"ensemble mean (N=" + str(n_ens) + r"). "
        r"\emph{Blur} $=(R_{\mathrm{HF}}^{\mathrm{single}} - "
        r"R_{\mathrm{HF}}^{\mathrm{ens}}) / R_{\mathrm{HF}}^{\mathrm{single}} \cdot 100\%$; "
        r"positive means the ensemble mean loses HF energy versus a single sample. "
        r"Averaged over " + str(n_samp) + r" (date, start-hour) windows on the 2020 test year.}"
    )
    lines.append(r"\label{tab:sh_ens_blur}")
    lines.append(r"\small")
    lines.append(r"\begin{tabular}{lcccr}")
    lines.append(r"\toprule")
    lines.append(
        r"Channel & $R_{\mathrm{HF}}^{\mathrm{GT}}$ & "
        r"$R_{\mathrm{HF}}^{\mathrm{single}}$ & "
        r"$R_{\mathrm{HF}}^{\mathrm{ens}}$ & "
        r"Blur \% \\")
    lines.append(r"\midrule")
    def _fmt(v: float) -> str:
        # Use scientific notation for tiny values that would round to 0.0000.
        if v < 5e-4 and v > 0:
            mant, exp = f"{v:.2e}".split("e")
            return f"${mant}\\!\\times\\!10^{{{int(exp)}}}$"
        return f"{v:.4f}"

    for r in rows:
        lines.append(
            f"{r['channel']} & {_fmt(r['R_HF_gt'])} & {_fmt(r['R_HF_single'])} & "
            f"{_fmt(r['R_HF_ens'])} & {r['relative_blur_pct']:+.2f} \\\\"
        )
    lines.append(r"\midrule")
    if agg:
        lines.append(
            f"\\textbf{{mean}} & {agg['mean_R_HF_gt']:.4f} & "
            f"{agg['mean_R_HF_single']:.4f} & "
            f"{agg['mean_R_HF_ens']:.4f} & "
            f"{agg['mean_relative_blur_pct']:+.2f} \\\\"
        )
    lines.append(r"\bottomrule")
    lines.append(r"\end{tabular}")
    lines.append(r"\end{table}")

    out = Path(args.out)
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text("\n".join(lines) + "\n")
    print(f"saved {out}")


if __name__ == "__main__":
    main()
