#!/usr/bin/env python3
"""Per-channel-class breakdown of 12h ep10 leaderboard.

Pure-JSON analysis: groups the 24 channels into physical classes and reports
mean RMSE_norm per (model, class) averaged over τ ∈ {1..11}.  This is a
surrogate for the per-region × per-season breakdown that would require a
fresh model + memmap run on the cluster (see launch script
``scripts/run_region_season_12h.sh`` for that path).

Channel classes (24 channels total in strict ep10 JSONs):
  - Temperature PL:  T1000, T925, T850, T700  (4)
  - Wind-U PL:       U1000, U925, U850, U700  (4)
  - Wind-V PL:       V1000, V925, V850, V700  (4)
  - Humidity PL:     Q1000, Q925, Q850, Q700  (4)
  - Geopotential:    Z1000, Z925, Z850, Z700  (4)
  - Surface:         t2m, u10, v10, mslp       (4)

Outputs:
  - metrics/eval_12h_2020_ep10/channel_class_breakdown.json
  - paper/tab_channel_class_12h.tex
"""
from __future__ import annotations

import argparse
import json
from pathlib import Path
from typing import Dict, List

import numpy as np

CHANNEL_CLASSES: Dict[str, List[str]] = {
    "T_PL":     ["T1000", "T925", "T850", "T700"],
    "U_PL":     ["U1000", "U925", "U850", "U700"],
    "V_PL":     ["V1000", "V925", "V850", "V700"],
    "Q_PL":     ["Q1000", "Q925", "Q850", "Q700"],
    "Z_PL":     ["Z1000", "Z925", "Z850", "Z700"],
    "Surface":  ["t2m", "u10", "v10", "mslp"],
}

CLASS_DISPLAY = {
    "T_PL":    r"$T$ (PL)",
    "U_PL":    r"$u$ (PL)",
    "V_PL":    r"$v$ (PL)",
    "Q_PL":    r"$q$ (PL)",
    "Z_PL":    r"$z$ (PL)",
    "Surface": "Surface",
}

TAG_DISPLAY = {
    "ATM-VFI_3yr_12h_fibo":          "ATM-VFI",
    "DC-AE_NoSkip_3yr_12h_fibo":     "DC-AE NoSkip",
    "WeatherDCAE_NoSkip_6yr_12h":    "WeatherDCAE (6yr,ep6*)",
    "DC-AE_Skip_3yr_12h_fibo":       "DC-AE Skip",
    "FuXi_3yr_12h_fibo":             "SwinV2",
    "SDyff_3yr_12h_fibo":            "S-DYff",
    "ModAFNO_3yr_12h_fibo":          "ModAFNO",
}


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--metrics-dir", default="metrics/eval_12h_2020_ep10")
    ap.add_argument("--out-json", default="metrics/eval_12h_2020_ep10/channel_class_breakdown.json")
    ap.add_argument("--out-tex", default="paper/tab_channel_class_12h.tex")
    args = ap.parse_args()

    metrics_dir = Path(args.metrics_dir)
    json_paths = sorted(p for p in metrics_dir.glob("*.json")
                        if p.name not in ("bootstrap_ci_95.json",
                                          "channel_class_breakdown.json"))

    records = []
    for p in json_paths:
        d = json.load(open(p))
        per_tau = d.get("per_tau", {})
        if not per_tau:
            continue
        class_to_vals: Dict[str, List[float]] = {cls: [] for cls in CHANNEL_CLASSES}
        for tau_s, by_method in per_tau.items():
            block = by_method.get("model", {})
            for cls, ch_list in CHANNEL_CLASSES.items():
                for c in ch_list:
                    v = block.get(f"rmse_norm_{c}")
                    if v is not None:
                        class_to_vals[cls].append(float(v))
        class_means = {cls: float(np.mean(vs)) if vs else None
                       for cls, vs in class_to_vals.items()}
        class_stds = {cls: float(np.std(vs, ddof=1)) if len(vs) > 1 else None
                      for cls, vs in class_to_vals.items()}
        records.append({
            "model_stem": p.stem,
            "display_name": TAG_DISPLAY.get(p.stem, p.stem),
            "per_class_mean": class_means,
            "per_class_std": class_stds,
            "n_tau": len(per_tau),
        })

    records.sort(key=lambda r: np.mean([v for v in r["per_class_mean"].values()
                                        if v is not None]))

    payload = {
        "schema_version": 1,
        "channel_classes": CHANNEL_CLASSES,
        "metric": "mean(rmse_norm) over τ∈{1..11} per channel-class",
        "records": records,
    }
    Path(args.out_json).parent.mkdir(parents=True, exist_ok=True)
    Path(args.out_json).write_text(json.dumps(payload, indent=2))
    print(f"saved {args.out_json}")

    # Build LaTeX table — class winners highlighted
    class_order = list(CHANNEL_CLASSES.keys())
    # find best per class
    best_per_class: Dict[str, float] = {}
    for cls in class_order:
        vals = [r["per_class_mean"].get(cls) for r in records]
        vals = [v for v in vals if v is not None]
        if vals:
            best_per_class[cls] = min(vals)

    lines = []
    lines.append("% Auto-generated by tools/eval/channel_class_12h.py")
    lines.append("% Surrogate for per-region breakdown (requires fresh model run; see")
    lines.append("%   scripts/run_region_season_12h.sh for the cluster-launch path).")
    lines.append(r"\begin{table*}[t]")
    lines.append(r"\centering")
    lines.append(r"\caption{Per-channel-class mean RMSE$_{\mathrm{norm}}$ for the "
                 r"12\,h leaderboard on 2020 ERA5 0.5\textdegree (averaged over "
                 r"$\tau \in \{1..11\}$). PL classes group $(z=1000, 925, 850, 700)$ "
                 r"levels. Class-best in \textbf{bold}. ModAFNO row dominated by "
                 r"catastrophic wind-PL RMSE at unseen $\tau$.}")
    lines.append(r"\label{tab:channel_class_12h}")
    lines.append(r"\small")
    lines.append(r"\setlength{\tabcolsep}{5pt}")
    lines.append(r"\begin{tabular}{l" + "r" * (len(class_order) + 1) + "}")
    lines.append(r"\toprule")
    head_cells = " & ".join(f"\\textbf{{{CLASS_DISPLAY[c]}}}" for c in class_order)
    lines.append(r"\textbf{Model} & " + head_cells + r" & \textbf{Mean} \\")
    lines.append(r"\midrule")
    for r in records:
        cells = []
        per_class = r["per_class_mean"]
        all_vals = [v for v in per_class.values() if v is not None]
        for cls in class_order:
            v = per_class.get(cls)
            if v is None:
                cells.append("--")
                continue
            s = f"{v:.3f}"
            if abs(v - best_per_class.get(cls, 1e9)) < 1e-9:
                s = r"\textbf{" + s + "}"
            cells.append(s)
        mean_str = f"{np.mean(all_vals):.3f}" if all_vals else "--"
        lines.append(f"{r['display_name']} & " + " & ".join(cells)
                     + f" & {mean_str} \\\\")
    lines.append(r"\bottomrule")
    lines.append(r"\end{tabular}")
    lines.append(r"\end{table*}")

    Path(args.out_tex).parent.mkdir(parents=True, exist_ok=True)
    Path(args.out_tex).write_text("\n".join(lines) + "\n")
    print(f"saved {args.out_tex}")

    # Console summary
    print("\n=== Class-best (lowest mean RMSE_norm per class) ===")
    for cls in class_order:
        best_rec = min((r for r in records if r["per_class_mean"].get(cls) is not None),
                       key=lambda r: r["per_class_mean"][cls])
        v = best_rec["per_class_mean"][cls]
        print(f"  {cls:8s}  {best_rec['display_name']:30s}  RMSE_norm={v:.4f}")


if __name__ == "__main__":
    main()
