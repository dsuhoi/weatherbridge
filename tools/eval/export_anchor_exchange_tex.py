#!/usr/bin/env python3
"""Export the retained anchor-exchange diagnostic for the two main models."""
from __future__ import annotations

import argparse
import hashlib
import json
import os
from pathlib import Path


MODELS = {
    "WeatherBridge": "flow_spectral",
    "WeatherDCAE-14M": "weatherdcae_14m_6yr",
}


def _sha256(path: Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()


def _load(path: Path, year: int) -> dict:
    payload = json.loads(path.read_text())
    npz_path = path.parent / payload.get("paired_windows_file", "")
    if (
        payload.get("schema_version") != 2
        or payload.get("diagnostic_only") is not True
        or payload.get("test_year") != year
        or payload.get("delta_t_hours") != 6
        or payload.get("eval_hours") != [1, 2, 3, 4, 5]
        or payload.get("channel_names") is None
        or len(payload["channel_names"]) != 24
        or payload.get("evaluation_protocol", {}).get("n_windows") != 240
        or payload.get("evaluation_protocol", {}).get("n_endpoints") != 48
        or not npz_path.is_file()
        or npz_path.stat().st_size != payload.get("paired_windows_size_bytes")
        or _sha256(npz_path) != payload.get("paired_windows_sha256")
        or not set(MODELS.values()).issubset(payload.get("models", {}))
    ):
        raise ValueError(f"invalid anchor-exchange artifact: {path}")
    return payload


def export_tex(artifact_2020: Path, artifact_2021: Path, output: Path) -> None:
    payloads = {
        2020: _load(artifact_2020, 2020),
        2021: _load(artifact_2021, 2021),
    }
    lines = [
        "% Auto-generated by tools/eval/export_anchor_exchange_tex.py",
        r"\begin{table}[!ht]",
        r"\centering",
        r"\caption{Anchor-exchange diagnostic on the six-hour task. Exchange RMSE compares $f(x_0,x_T,t)$ with $f(x_T,x_0,1-t)$; forward RMSE compares the first prediction with ERA5. Lower is better. The 48-endpoint, 240-window sample per year is diagnostic and was not used for selection.}",
        r"\label{tab:anchor-exchange}",
        r"\begin{tabular}{llrrr}",
        r"\toprule",
        r"Model & Year & Exchange RMSE & Forward RMSE & Ratio \\",
        r"\midrule",
    ]
    for label, key in MODELS.items():
        for year in (2020, 2021):
            row = payloads[year]["models"][key]
            lines.append(
                f"{label} & {year} & "
                f"{row['exchange']['pooled_rmse']:.3f} & "
                f"{row['forward_error']['pooled_rmse']:.3f} & "
                f"{row['exchange_to_forward_rmse_ratio']:.2f} \\\\"
            )
    lines.extend([r"\bottomrule", r"\end{tabular}", r"\end{table}"])
    output.parent.mkdir(parents=True, exist_ok=True)
    temporary = output.with_suffix(output.suffix + ".tmp")
    temporary.write_text("\n".join(lines) + "\n")
    os.replace(temporary, output)


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--artifact-2020", type=Path, required=True)
    parser.add_argument("--artifact-2021", type=Path, required=True)
    parser.add_argument("--output", type=Path, required=True)
    args = parser.parse_args()
    export_tex(args.artifact_2020, args.artifact_2021, args.output)


if __name__ == "__main__":
    main()
