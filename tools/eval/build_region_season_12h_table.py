#!/usr/bin/env python3
"""Build paper/tab_region_season_12h.tex from metrics/region_season_12h/*.json.

Mirrors tools/eval/build_region_season_table.py but for the 12 h pipeline
(7 geographic regions × 4 seasons; land/ocean diagnostics are retained in
the source artifacts but omitted from this compact paper table).

Until ``metrics/region_season_12h/`` is populated (requires fresh model
inference on the cluster — see scripts/run_region_season_12h.sh), the
table emits a placeholder LaTeX block with the launch instructions.
"""
from __future__ import annotations

import argparse
import json
from pathlib import Path
from typing import Dict, List

import numpy as np


REGIONS = [
    "Tropics", "N-Extra", "S-Extra", "Arctic", "Antarctic",
    "North_Atlantic", "West_Pacific",
]
REGION_DISPLAY = {
    "Tropics":        "Tropics",
    "N-Extra":        "N-extratrop.",
    "S-Extra":        "S-extratrop.",
    "Arctic":         "Arctic",
    "Antarctic":      "Antarctic",
    "North_Atlantic": "N-Atlantic",
    "West_Pacific":   "W-Pacific",
}
SEASONS = ["DJF", "MAM", "JJA", "SON"]

MODEL_ORDER = [
    ("DC-AE_NoSkip_3yr_12h_fibo",     "WeatherDCAE-14M (3yr)"),
    ("DC-AE_Skip_3yr_12h_fibo",       "WeatherDCAE-Skip (14M, 3yr)"),
    ("ModAFNO_3yr_12h_fibo",          "ModAFNO"),
    ("FuXi_3yr_12h_fibo",             "SwinV2"),
    ("SDyff_3yr_12h_fibo",            "S-DYff"),
    ("ATM-VFI_3yr_12h_fibo",          "ATM-VFI (24ch)"),
]


def _placeholder() -> str:
    return (
        "% Auto-generated by tools/eval/build_region_season_12h_table.py\n"
        "% No per-region 12 h JSONs found — placeholder block.\n"
        "%\n"
        "% To produce the actual table:\n"
        "%   1. On a GPU host with weather_time_interp + memmap dataset, run:\n"
        "%       bash scripts/run_region_season_12h.sh\n"
        "%   2. rsync metrics/region_season_12h/*.json back to local\n"
        "%   3. python tools/eval/build_region_season_12h_table.py\n"
        r"\begin{table}[t]" + "\n"
        r"\centering" + "\n"
        r"\caption{Per-region $\times$ per-season RMSE$_{\mathrm{norm}}$ "
        r"breakdown for the 12\,h leaderboard "
        r"(\textit{pending cluster run}; ETA $\sim$70 min on B300).}" + "\n"
        r"\label{tab:region_season_12h}" + "\n"
        r"\small" + "\n"
        r"\begin{tabular}{ll" + ("c" * (len(SEASONS) + 1)) + "}" + "\n"
        r"\toprule" + "\n"
        r"Region & Model & "
        + " & ".join(SEASONS) + r" & Mean \\" + "\n"
        r"\midrule" + "\n"
        r"\multicolumn{" + str(2 + len(SEASONS) + 1) + r"}{c}{"
        r"\emph{pending cluster eval — see scripts/run\_region\_season\_12h.sh}}"
        r" \\" + "\n"
        r"\bottomrule" + "\n"
        r"\end{tabular}" + "\n"
        r"\end{table}" + "\n"
    )


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--metrics-dir", default="metrics/region_season_12h_2020")
    ap.add_argument("--out", default="paper/A5_region_season_12h_table.tex")
    args = ap.parse_args()

    metrics_dir = Path(args.metrics_dir)
    if not metrics_dir.exists() or not list(metrics_dir.glob("*.json")):
        Path(args.out).parent.mkdir(parents=True, exist_ok=True)
        Path(args.out).write_text(_placeholder())
        print(f"saved placeholder {args.out}")
        return

    # Real path: data exists.
    data: Dict[str, dict] = {}
    for stem, _ in MODEL_ORDER:
        p = metrics_dir / f"{stem}.json"
        if p.exists():
            data[stem] = json.load(open(p))

    # For each (region, season) find the best (lowest) RMSE across models so
    # we can bold the winning cell. Iterate twice: first to gather, then to
    # format with bolding.
    best_per_rs: Dict[str, Dict[str, float]] = {r: {} for r in REGIONS}
    raw: Dict[str, Dict[str, Dict[str, float]]] = {r: {} for r in REGIONS}
    for region in REGIONS:
        for stem, _disp in MODEL_ORDER:
            if stem not in data:
                continue
            d = data[stem]
            for season in SEASONS:
                entry = d["per_region_season"].get(region, {}).get(season, {})
                v = entry.get("rmse_norm_avg")
                if v is None:
                    continue
                raw[region].setdefault(stem, {})[season] = float(v)
                cur = best_per_rs[region].get(season, float("inf"))
                if v < cur:
                    best_per_rs[region][season] = float(v)

    rows = []
    for region in REGIONS:
        for stem, disp in MODEL_ORDER:
            if stem not in data:
                continue
            cells = []
            season_vals = []
            for season in SEASONS:
                v = raw[region].get(stem, {}).get(season)
                if v is None:
                    cells.append("--")
                    season_vals.append(float("nan"))
                else:
                    txt = f"{v:.3f}"
                    if abs(v - best_per_rs[region].get(season, float("nan")))\
                            < 1e-9:
                        txt = rf"\textbf{{{txt}}}"
                    cells.append(txt)
                    season_vals.append(float(v))
            valid = [v for v in season_vals if not np.isnan(v)]
            mean_s = f"{np.mean(valid):.3f}" if valid else "--"
            rows.append((region, disp, cells, mean_s))

    lines = []
    lines.append("% Auto-generated by tools/eval/build_region_season_12h_table.py")
    lines.append(r"\begin{table*}[t]")
    lines.append(r"\centering")
    missing_models = [
        disp for stem, disp in MODEL_ORDER if stem not in data
    ]
    if missing_models:
        miss_note = (
            r" \emph{Missing models: " + ", ".join(missing_models) +
            r"; see commit log for trainer regression notes.}"
        )
    else:
        miss_note = ""
    lines.append(r"\caption{Per-region $\times$ per-season normalised RMSE for "
                 r"the 12\,h leaderboard on 2020 ERA5 0.5\textdegree (averaged "
                 r"over channels and over $\tau \in \{1..11\}$). 7 regions "
                 r"(5 zonal bands + 2 basin boxes); 4 seasons. "
                 r"Bold = best per (region, season) cell." + miss_note + "}")
    lines.append(r"\label{tab:region_season_12h}")
    lines.append(r"\small")
    lines.append(r"\setlength{\tabcolsep}{4pt}")
    lines.append(r"\begin{tabular}{ll" + "r" * len(SEASONS) + "r}")
    lines.append(r"\toprule")
    seas_hdr = " & ".join(s for s in SEASONS)
    lines.append(rf"\textbf{{Region}} & \textbf{{Model}} & {seas_hdr} & "
                 r"\textbf{Mean} \\")
    lines.append(r"\midrule")
    cur_region = None
    for region, disp, cells, mean_s in rows:
        r_label = REGION_DISPLAY[region] if region != cur_region else ""
        if region != cur_region and cur_region is not None:
            lines.append(r"\midrule")
        cur_region = region
        lines.append(f"{r_label} & {disp} & " + " & ".join(cells) +
                     f" & {mean_s} \\\\")
    lines.append(r"\bottomrule")
    lines.append(r"\end{tabular}")
    lines.append(r"\end{table*}")

    Path(args.out).parent.mkdir(parents=True, exist_ok=True)
    Path(args.out).write_text("\n".join(lines) + "\n")
    print(f"saved {args.out}")


if __name__ == "__main__":
    main()
