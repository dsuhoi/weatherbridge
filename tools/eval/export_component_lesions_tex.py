#!/usr/bin/env python3
"""Export same-checkpoint WeatherBridge inference lesions as a LaTeX table."""
from __future__ import annotations

import argparse
import json
import math
import os
from pathlib import Path
from typing import Any


_HYDROSTATIC_FIELDS = (
    ("Z1000", r"$Z_{1000}$"),
    ("Z925", r"$Z_{925}$"),
    ("Z850", r"$Z_{850}$"),
    ("Z700", r"$Z_{700}$"),
    ("mslp", "MSLP"),
)


def _comparison(path: Path) -> dict[str, Any]:
    payload = json.loads(path.read_text())
    comparisons = payload.get("comparisons", {})
    if set(comparisons) != {"weatherbridge"}:
        raise ValueError(f"{path}: expected one WeatherBridge comparison")
    result = comparisons["weatherbridge"]
    if result.get("n_windows") != 7315 or result.get("n_blocks") != 53:
        raise ValueError(f"{path}: unexpected paired index")
    for key in ("left_rmse", "right_rmse", "relative_delta_pct"):
        if not math.isfinite(float(result[key])):
            raise ValueError(f"{path}: non-finite {key}")
    return result


def render_table(
    acceleration: dict[str, Any],
    transport: dict[str, Any],
    hydrostatic: dict[str, Any],
) -> str:
    references = [
        float(result["right_rmse"])
        for result in (acceleration, transport, hydrostatic)
    ]
    if not all(
        math.isclose(references[0], value, rel_tol=0.0, abs_tol=1.0e-12)
        for value in references[1:]
    ):
        raise ValueError("lesions do not share the intact-model reference")
    per_channel_tau = hydrostatic.get("per_channel_tau", {})
    if set(per_channel_tau) != {"1", "2", "3", "4", "5"}:
        raise ValueError("hydrostatic lesion requires all five query hours")
    hydrostatic_rows = []
    for field, label in _HYDROSTATIC_FIELDS:
        cells = [per_channel_tau[str(hour)][field] for hour in range(1, 6)]
        left = math.fsum(float(cell["left_rmse"]) for cell in cells) / len(cells)
        right = math.fsum(float(cell["right_rmse"]) for cell in cells) / len(cells)
        hourly_changes = [
            100.0 * (float(cell["left_rmse"]) / float(cell["right_rmse"]) - 1.0)
            for cell in cells
        ]
        hydrostatic_rows.append(
            (
                label,
                right,
                left,
                100.0 * (left / right - 1.0),
                min(hourly_changes),
                max(hourly_changes),
            )
        )
    rows = [
        ("Intact WeatherBridge", acceleration["right_rmse"], 0.0, 0.0),
        (
            "Acceleration disabled",
            acceleration["left_rmse"],
            acceleration["delta_left_minus_right"],
            acceleration["relative_delta_pct"],
        ),
        (
            "Warped-anchor transport disabled",
            transport["left_rmse"],
            transport["delta_left_minus_right"],
            transport["relative_delta_pct"],
        ),
        (
            "Hydrostatic head disabled",
            hydrostatic["left_rmse"],
            hydrostatic["delta_left_minus_right"],
            hydrostatic["relative_delta_pct"],
        ),
    ]
    lines = [
        "% Auto-generated by tools/eval/export_component_lesions_tex.py",
        r"\begin{table}[!ht]",
        r"\centering",
        (
            r"\caption{Same-checkpoint inference lesions on the full-year 2020 "
            r"six-hour index. No arm is retrained. Positive $\Delta$ and percentage "
            r"values denote degradation relative to intact WeatherBridge. "
            r"All three aggregate lesion tests reach the Monte Carlo "
            r"resolution limit ($1/5001$) under paired seven-day-block permutation. "
            r"Panel b resolves the hydrostatic lesion over geopotential $Z$ at four "
            r"pressure levels and mean sea-level pressure (MSLP); "
            r"RMSE and percentage change are computed from averages across the five "
            r"query hours, followed by the minimum--maximum hourly change in brackets.}"
        ),
        r"\label{tab:component-lesions}",
        r"\small",
        r"\setlength{\tabcolsep}{4pt}",
        r"\begin{tabularx}{\textwidth}{@{}>{\raggedright\arraybackslash}Xrrr@{}}",
        r"\multicolumn{4}{@{}l}{\textbf{a. Aggregate lesions}} \\",
        r"\toprule",
        (
            r"Inference arm & RMSE & $\Delta$ vs intact & Change (\%) \\"
        ),
        r"\midrule",
    ]
    for label, rmse, delta, change in rows:
        lines.append(
            f"{label} & {float(rmse):.5f} & {float(delta):+.5f} & "
            f"{float(change):+.2f}" + r" \\"
        )
    lines.extend(
        (
            r"\bottomrule",
            r"\end{tabularx}",
            r"\medskip",
            r"\begin{tabularx}{\textwidth}{@{}>{\raggedright\arraybackslash}Xrrr@{}}",
            r"\multicolumn{4}{@{}l}{\textbf{b. Hydrostatic-head target fields}} \\",
            r"\toprule",
            (
                r"Field & Intact RMSE & Head-off RMSE & Change (\%) \\"
            ),
            r"\midrule",
        )
    )
    for (
        label,
        intact,
        head_off,
        change,
        minimum,
        maximum,
    ) in hydrostatic_rows:
        lines.append(
            f"{label} & {intact:.5f} & {head_off:.5f} & "
            f"{change:+.2f} [{minimum:+.2f}, {maximum:+.2f}]"
            + r" \\"
        )
    lines.extend((r"\bottomrule", r"\end{tabularx}", r"\end{table}"))
    return "\n".join(lines) + "\n"


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--acceleration", type=Path, required=True)
    parser.add_argument("--transport", type=Path, required=True)
    parser.add_argument("--hydrostatic", type=Path, required=True)
    parser.add_argument(
        "--out-tex",
        type=Path,
        default=Path("paper/tab_component_lesions.tex"),
    )
    args = parser.parse_args()
    rendered = render_table(
        _comparison(args.acceleration),
        _comparison(args.transport),
        _comparison(args.hydrostatic),
    )
    args.out_tex.parent.mkdir(parents=True, exist_ok=True)
    temporary = args.out_tex.with_suffix(args.out_tex.suffix + ".tmp")
    temporary.write_text(rendered)
    os.replace(temporary, args.out_tex)
    print(f"wrote {args.out_tex}")


if __name__ == "__main__":
    main()
