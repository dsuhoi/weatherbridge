#!/usr/bin/env python3
"""HF-preservation summary from existing 12h SH spectra NPZ files.

Reads metrics/sh_spectra_12h_ep10/*.npz (6 models × 4 τ × 5 channels)
and outputs:

  1. metrics/sh_spectra_12h_ep10/hf_preservation_summary.json
     — per (model, τ, channel) HF ratio = ΣE_pred(ℓ ≥ ℓ_lo) / ΣE_gt(...)
     — and aggregate ranking averaged over channels + τ.
  2. paper/tab_sh_hf_preservation_12h.tex — compact per-model summary
     row table for inclusion in the discussion section.

The same pipeline applies to 6h once metrics/sh_spectra_6h_v1_hf_preservation/*.npz is
populated (see scripts/run_sh_spectra_6h.sh for that — deferred to
cluster).
"""
from __future__ import annotations

import argparse
import json
from pathlib import Path
from typing import Dict, List

import numpy as np


MODEL_DISPLAY = {
    "DC-AE_NoSkip_3yr_12h_fibo":      "DC-AE NoSkip (3yr)",
    "DC-AE_Skip_3yr_12h_fibo":        "DC-AE Skip (3yr)",
    "FuXi_3yr_12h_fibo":              "SwinV2",
    "ModAFNO_3yr_12h_fibo":           "ModAFNO",
    "SDyff_3yr_12h_fibo":             "S-DYff",
    "ATM-VFI_3yr_12h_fibo":           "ATM-VFI",
    "WeatherDCAE_NoSkip_6yr_12h":     "WeatherDCAE (6yr,ep6*)",
}


def _hf_ratio(pred_El: np.ndarray, gt_El: np.ndarray, ell_lo: int) -> float:
    p = pred_El[ell_lo:].sum()
    g = max(float(gt_El[ell_lo:].sum()), 1e-30)
    return float(p / g)


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--npz-dir", default="metrics/sh_spectra_12h_ep10")
    ap.add_argument("--out-json", default=None,
                    help="default: <npz-dir>/hf_preservation_summary.json")
    ap.add_argument("--out-tex", default="paper/tab_sh_hf_preservation_12h.tex")
    ap.add_argument("--hf-frac", type=float, default=0.5,
                    help="ℓ_lo = floor(hf_frac × lmax) (default 0.5)")
    args = ap.parse_args()

    npz_dir = Path(args.npz_dir)
    out_json = Path(args.out_json or npz_dir / "hf_preservation_summary.json")
    out_tex = Path(args.out_tex)

    # Collect per (model, τ, channel) entries.
    rows: List[dict] = []
    per_model: Dict[str, List[float]] = {}
    for p in sorted(npz_dir.glob("*.npz")):
        d = np.load(p, allow_pickle=True)
        model_name = str(d["model_name"]) if "model_name" in d.files else p.stem
        tau = int(d["tau"]) if "tau" in d.files else -1
        ell = d["ell"]
        ell_lo = max(1, int(args.hf_frac * int(ell.max())))
        channels = [str(c) for c in d["channel_names"]]
        for ci, ch in enumerate(channels):
            r = _hf_ratio(d["pred_El"][ci], d["gt_El"][ci], ell_lo)
            rows.append({
                "model_stem": model_name,
                "display_name": MODEL_DISPLAY.get(model_name, model_name),
                "tau": tau,
                "channel": ch,
                "hf_ratio": round(r, 4),
                "ell_lo": ell_lo,
                "lmax": int(ell.max()),
            })
            per_model.setdefault(model_name, []).append(r)

    summary = []
    for m_stem, vals in per_model.items():
        a = np.array(vals)
        summary.append({
            "model_stem": m_stem,
            "display_name": MODEL_DISPLAY.get(m_stem, m_stem),
            "mean_hf_ratio": round(float(a.mean()), 4),
            "median_hf_ratio": round(float(np.median(a)), 4),
            "std_hf_ratio": round(float(a.std(ddof=1)), 4),
            "min_hf_ratio": round(float(a.min()), 4),
            "max_hf_ratio": round(float(a.max()), 4),
            "n_samples": len(vals),
        })
    summary.sort(key=lambda r: r["mean_hf_ratio"], reverse=True)  # higher = better

    payload = {
        "schema_version": 1,
        "metric": ("HF energy ratio = sum_{l >= l_lo} E_pred(l) / "
                   "sum_{l >= l_lo} E_gt(l). Closer to 1 = better."),
        "hf_frac": args.hf_frac,
        "rows": rows,
        "per_model_summary": summary,
    }
    out_json.write_text(json.dumps(payload, indent=2))
    print(f"saved {out_json}")

    # Console
    print("\n=== HF preservation ranking (higher = better, 1.0 = perfect) ===")
    for r in summary:
        print(f"  {r['display_name']:30s}  "
              f"mean={r['mean_hf_ratio']:.3f}  "
              f"median={r['median_hf_ratio']:.3f}  "
              f"std={r['std_hf_ratio']:.3f}  "
              f"[{r['min_hf_ratio']:.3f} … {r['max_hf_ratio']:.3f}]  "
              f"(n={r['n_samples']})")

    # LaTeX
    lines = []
    lines.append("% Auto-generated by tools/eval/analyze_sh_hf_preservation.py")
    lines.append("% Source: metrics/sh_spectra_12h_ep10/*.npz (6 models × 4 τ × 5 channels)")
    lines.append(r"\begin{table}[t]")
    lines.append(r"\centering")
    lines.append(r"\caption{Spherical-harmonic high-frequency preservation "
                 r"ratio $R_{\mathrm{HF}} = \sum_{\ell \geq \ell_{\mathrm{lo}}} "
                 r"E_{\mathrm{pred}}(\ell) / \sum_{\ell \geq \ell_{\mathrm{lo}}} "
                 r"E_{\mathrm{GT}}(\ell)$ for the 12\,h leaderboard, averaged "
                 r"over $\tau \in \{2, 3, 5, 8\}$ and 5 surface/PL channels. "
                 r"$\ell_{\mathrm{lo}} = \lceil 0.5 \cdot \ell_{\max} \rceil = 90$. "
                 r"$R_{\mathrm{HF}} = 1$ = perfect spectral fidelity. "
                 r"Bold = highest mean.}")
    lines.append(r"\label{tab:sh_hf_preservation_12h}")
    lines.append(r"\small")
    lines.append(r"\begin{tabular}{lrrrr}")
    lines.append(r"\toprule")
    lines.append(r"Model & mean & median & range & $n$ \\")
    lines.append(r"\midrule")
    best = summary[0]["mean_hf_ratio"]
    for r in summary:
        m = r["mean_hf_ratio"]
        m_str = f"{m:.3f}"
        if abs(m - best) < 1e-9:
            m_str = r"\textbf{" + m_str + "}"
        lines.append(
            f"{r['display_name']} & {m_str} & {r['median_hf_ratio']:.3f} & "
            f"[{r['min_hf_ratio']:.3f}, {r['max_hf_ratio']:.3f}] & "
            f"{r['n_samples']} \\\\"
        )
    lines.append(r"\bottomrule")
    lines.append(r"\end{tabular}")
    lines.append(r"\end{table}")
    out_tex.parent.mkdir(parents=True, exist_ok=True)
    out_tex.write_text("\n".join(lines) + "\n")
    print(f"\nsaved {out_tex}")


if __name__ == "__main__":
    main()
