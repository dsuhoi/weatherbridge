#!/usr/bin/env python3
"""Stratify six-hour interpolation RMSE by anchor start hour in UTC."""

from __future__ import annotations

import argparse
import hashlib
import json
from pathlib import Path
from typing import Any

import numpy as np


STARTS = (0, 6, 12, 18)
STRATA = {
    "00": (0,),
    "06": (6,),
    "12": (12,),
    "18": (18,),
    "within_window": (0, 12),
    "crosses_window_boundary": (6, 18),
}


def _sha256(path: Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()


def _load(path: Path) -> dict[str, np.ndarray]:
    with np.load(path, allow_pickle=False) as artifact:
        required = {
            "year",
            "t0",
            "tau",
            "channel_names",
            "mse_norm_model",
            "mse_norm_bilinear",
        }
        missing = required - set(artifact.files)
        if missing:
            raise ValueError(f"{path}: missing arrays {sorted(missing)}")
        return {name: np.asarray(artifact[name]) for name in required}


def _score(mse: np.ndarray, mask: np.ndarray) -> float:
    if not np.any(mask):
        raise ValueError("UTC stratum is empty")
    return float(np.sqrt(np.mean(mse[mask], axis=0)).mean())


def summarize_year(weatherbridge_path: Path, dcae_path: Path, year: int) -> dict[str, Any]:
    weatherbridge = _load(weatherbridge_path)
    dcae = _load(dcae_path)
    for key in ("year", "t0", "tau", "channel_names"):
        if not np.array_equal(weatherbridge[key], dcae[key]):
            raise ValueError(f"unpaired WeatherBridge and WeatherDCAE arrays: {key}")
    if set(np.unique(weatherbridge["year"]).tolist()) != {year}:
        raise ValueError("artifact year does not match the requested year")
    if not np.allclose(
        weatherbridge["mse_norm_bilinear"],
        dcae["mse_norm_bilinear"],
        rtol=0.0,
        atol=2e-6,
    ):
        raise ValueError("linear-interpolation arrays are not paired")

    start_hour = weatherbridge["t0"].astype(np.int64) % 24
    if set(np.unique(start_hour).tolist()) != set(STARTS):
        raise ValueError("expected 00, 06, 12 and 18 UTC starts")
    rows: dict[str, Any] = {}
    for label, hours in STRATA.items():
        mask = np.isin(start_hour, hours)
        bridge_score = _score(weatherbridge["mse_norm_model"], mask)
        dcae_score = _score(dcae["mse_norm_model"], mask)
        linear_score = _score(weatherbridge["mse_norm_bilinear"], mask)
        rows[label] = {
            "start_hours_utc": list(hours),
            "n_window_hours": int(mask.sum()),
            "weatherbridge_rmse": bridge_score,
            "weatherdcae_rmse": dcae_score,
            "linear_rmse": linear_score,
            "weatherbridge_gain_vs_dcae_pct": 100.0
            * (dcae_score - bridge_score)
            / dcae_score,
            "weatherbridge_gain_vs_linear_pct": 100.0
            * (linear_score - bridge_score)
            / linear_score,
        }
    return {
        "year": year,
        "weatherbridge_path": str(weatherbridge_path),
        "weatherbridge_sha256": _sha256(weatherbridge_path),
        "weatherdcae_path": str(dcae_path),
        "weatherdcae_sha256": _sha256(dcae_path),
        "rows": rows,
    }


def render_tex(report: dict[str, Any]) -> str:
    labels = (
        ("00", "00 (within)"),
        ("06", "06 (crosses 09 UTC)"),
        ("12", "12 (within)"),
        ("18", "18 (crosses 21 UTC)"),
        ("within_window", "Within-window pooled"),
        ("crosses_window_boundary", "Boundary-crossing pooled"),
    )
    lines = [
        r"% Auto-generated by tools/eval/summarize_utc_start_strata.py",
        r"\begin{table}[!ht]",
        r"\centering",
        r"\caption{Six-hour RMSE stratified by anchor start time. Starts at 00 "
        r"and 12 UTC keep both anchors in one ERA5 4D-Var window; starts at 06 "
        r"and 18 UTC cross the 09 or 21 UTC boundary. Scores are mean "
        r"channel-wise normalised RMSE on the paired full-year index.}",
        r"\label{tab:utc-start-strata}",
        r"\small",
    ]
    by_year = {str(row["year"]): row["rows"] for row in report["years"]}
    for year in ("2020", "2021"):
        lines.extend(
            [
                rf"\textbf{{{year}}}\\[0.25em]",
                r"\begin{tabular}{lrrrr}",
                r"\toprule",
                r"Start UTC & WB & DCAE & Linear & WB vs DCAE \\",
                r"\midrule",
            ]
        )
        for key, display in labels:
            row = by_year[year][key]
            values = [
                f"{row['weatherbridge_rmse']:.4f}",
                f"{row['weatherdcae_rmse']:.4f}",
                f"{row['linear_rmse']:.4f}",
                f"{row['weatherbridge_gain_vs_dcae_pct']:+.1f}\\%",
            ]
            lines.append(display + " & " + " & ".join(values) + r" \\")
        lines.extend([r"\bottomrule", r"\end{tabular}"])
        if year == "2020":
            lines.append(r"\par\vspace{0.6em}")
    lines.append(r"\end{table}")
    return "\n".join(lines) + "\n"


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    for year in (2020, 2021):
        parser.add_argument(f"--weatherbridge-{year}", type=Path, required=True)
        parser.add_argument(f"--dcae-{year}", type=Path, required=True)
    parser.add_argument("--out-json", type=Path, required=True)
    parser.add_argument("--out-tex", type=Path, required=True)
    args = parser.parse_args()
    report = {
        "schema_version": 1,
        "metric": "mean_channelwise_normalized_rmse",
        "years": [
            summarize_year(
                getattr(args, f"weatherbridge_{year}"),
                getattr(args, f"dcae_{year}"),
                year,
            )
            for year in (2020, 2021)
        ],
    }
    args.out_json.parent.mkdir(parents=True, exist_ok=True)
    args.out_tex.parent.mkdir(parents=True, exist_ok=True)
    args.out_json.write_text(json.dumps(report, indent=2) + "\n")
    args.out_tex.write_text(render_tex(report))
    print(f"wrote {args.out_json} and {args.out_tex}")


if __name__ == "__main__":
    main()
