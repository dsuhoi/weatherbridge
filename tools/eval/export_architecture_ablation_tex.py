#!/usr/bin/env python3
"""Export the transport-architecture ablation from the frozen selector."""
from __future__ import annotations

import argparse
import json
import math
import os
from pathlib import Path

VARIANTS = (
    (
        "flow_spectral",
        "WeatherBridge",
        "Transport trunk + spectral supervision",
    ),
    (
        "weatherbridge_detail",
        "Detail",
        "+ transported anchor-detail bypass",
    ),
    (
        "refine",
        "Refine",
        "Latent transformer; shared heads; no mass head",
    ),
)


def finite(value: object, context: str) -> float:
    result = float(value)
    if not math.isfinite(result):
        raise ValueError(f"{context}: non-finite value")
    return result


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--selector",
        type=Path,
        default=Path("metrics/journal_champion_v1/final.json"),
    )
    parser.add_argument(
        "--out-tex",
        type=Path,
        default=Path("paper/tab_architecture_ablation.tex"),
    )
    args = parser.parse_args()

    payload = json.loads(args.selector.read_text())
    if (
        payload.get("status") != "reference_retained"
        or payload.get("winner") != "weatherdcae_14m"
    ):
        raise ValueError("unexpected frozen-selector status")
    candidates = payload.get("candidates", {})
    rows = []
    for key, label, change in VARIANTS:
        candidate = candidates[key]
        evidence = candidate["evidence"]
        seeds = candidate["seed_confirmation"]
        if candidate.get("selection_pass") is not False:
            raise ValueError(f"{key}: unexpected frozen selection")
        six_rows = seeds["horizons"]["6"]["rows"]
        twelve_rows = seeds["horizons"]["12"]["rows"]
        if not six_rows or not twelve_rows:
            raise ValueError(f"{key}: missing HRES seed evidence")
        rows.append(
            (
                label,
                change,
                finite(candidate["parameters_m"], f"{key} parameters"),
                finite(
                    evidence["6h"]["2020"]["aggregate_rmse"],
                    f"{key} 6h 2020",
                ),
                finite(
                    evidence["6h"]["2021"]["aggregate_rmse"],
                    f"{key} 6h 2021",
                ),
                finite(
                    evidence["12h"]["2020"]["aggregate_rmse"],
                    f"{key} 12h 2020",
                ),
            )
        )

    lines = [
        "% Auto-generated by tools/eval/export_architecture_ablation_tex.py",
        r"\begin{table}[!ht]",
        r"\centering",
        (
            r"\caption{Transport-architecture ablation. RMSE is the 24-field "
            r"full-year mean; lower is better. Internal variants are confined "
            r"to this audit table; the main comparison uses WeatherBridge.}"
        ),
        r"\label{tab:architecture-ablation}",
        r"\footnotesize",
        r"\setlength{\tabcolsep}{3.5pt}",
        r"\begin{tabularx}{\textwidth}{@{}l>{\raggedright\arraybackslash}Xrrrr@{}}",
        r"\toprule",
        (
            r"Variant & Architectural difference & \shortstack{Params\\(M)} & "
            r"\shortstack{6\,h\\2020} & \shortstack{6\,h\\2021} & "
            r"\shortstack{12\,h\\2020} \\"
        ),
        r"\midrule",
    ]
    for (
        label,
        change,
        parameters,
        rmse_2020,
        rmse_2021,
        rmse_12h,
    ) in rows:
        lines.append(
            f"{label} & {change} & {parameters:.1f} & {rmse_2020:.4f} & "
            f"{rmse_2021:.4f} & {rmse_12h:.4f}" + r" \\"
        )
    lines.extend((r"\bottomrule", r"\end{tabularx}", r"\end{table}"))
    temporary = args.out_tex.with_suffix(args.out_tex.suffix + ".tmp")
    temporary.parent.mkdir(parents=True, exist_ok=True)
    temporary.write_text("\n".join(lines) + "\n")
    os.replace(temporary, args.out_tex)
    print(f"wrote {args.out_tex}")


if __name__ == "__main__":
    main()
